/*
Take two integers a = 17 and b = 5.

Print their sum, difference, product, quotient, and remainder.
*/

#include <stdio.h>

int main() {
    int a= 17, b = 5;
    printf("Sum: %d\n", a + b);
    printf("Difference: %d\n", a - b);
    printf("Product: %d\n", a * b);
    printf("Quotient: %d\n", a / b);
    printf("Remainder: %d\n", a % b);
    return 0;
}